def _edit_distance(a: str, b: str) -> int:
    if a == b:
        return 0
    if len(a) < len(b):
        a, b = b, a
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1,
                           prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]




def stat_name_of(text: str) -> str:
    """从「暴击卒 2.4%」里取出属性名部分「暴击卒」"""
    t = (text or "").strip()
    for sep in (" +", " ", "　"):
        i = t.find(sep)
        if i > 0:
            return t[:i]
    return t







