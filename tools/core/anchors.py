def detect_by_fingerprint(vision) -> str | None:
    """用界面指纹判定（比文字锚点可靠：靠区分度打分，不是命中一个词就认）。"""
    try:
        from . import fingerprint as fp
        data = fp.load()
        if not data:
            return None
        name, score, ok = fp.detect(vision, data)
        return name if ok else None
    except Exception:
        return None


def detect(vision, candidates: list[Anchor] | None = None) -> Anchor | None:
    """返回第一个匹配上的界面锚点。顺序即优先级。"""
    for a in (candidates or ANCHORS):
        try:
            if a.match(vision):
                return a
        except Exception:
            continue
    return None


def is_(vision, name: str) -> bool:
    """**文字锚点优先，指纹兜底**（和 describe 保持一致）。"""
    for a in ANCHORS:
        if a.name == name:
            if a.match(vision):
                return True
            # 文字没中，再看指纹（可能这个界面没有文字特征）
            return detect_by_fingerprint(vision) == name
    return False


def wait(vision, name: str, timeout: float = 10.0) -> bool:
    import time
    t0 = time.time()
    while time.time() - t0 < timeout:
        if is_(vision, name):
            return True
        time.sleep(0.15)
    return False


def describe(vision) -> str:
    """**文字锚点优先，指纹兜底。**

    为什么改（2026-11-26）：指纹是「打分最近者」，文字锚点是「must 全中」。
    实测点「更多」后，文字锚点明明能命中「更多功能」，
    但 `state/fingerprints.json` 里没有这个新面板，指纹把它归成了
    「驱动盘拆解页」—— **精确的被模糊的盖住了。**

    指纹的定位应该是「文字锚点认不出时兜底」，不是「优先」。
    """
    # **被遮挡时要说真话**（BUG-032）。
    # 此时读到的可能是别的程序的画面，任何「认出来了」都是假的。
    if getattr(vision, "occluded", False):
        return "被遮挡"

    a = detect(vision)                   # 精确：must 全中
    if a:
        return a.name
    fp_name = detect_by_fingerprint(vision)   # 兜底：打分最近
    return fp_name or "未知界面"