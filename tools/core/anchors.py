@dataclass
class Anchor:
    """一个界面的判定条件"""
    name: str
    region: Region                   # 检查区域
    must: tuple[str, ...] = ()       # 必须同时存在的关键词
    forbidden: tuple[str, ...] = ()  # 出现任何一个就否定
    note: str = ""

    def match(self, vision) -> bool:
        txt = vision.text(self.region)
        if any(f in txt for f in self.forbidden):
            return False
        return all(m in txt for m in self.must)


