def detect_by_fingerprint(vision) -> str | None:
    """用界面指纹判定（比文字锚点可靠：靠区分度打分，不是命中一个词就认）。"""
    try:
        from . import fingerprint as fp
        data = fp.load()
        if not data:
            return None
        name, score, ok = fp.detect(vision, data)
        return name if ok else None
    except Exception:
        return None


def detect(vision, candidates: list[Anchor] | None = None) -> Anchor | None:
    """返回第一个匹配上的界面锚点。顺序即优先级。"""
    for a in (candidates or ANCHORS):
        try:
            if a.match(vision):
                return a
        except Exception:
            continue
    return None


def is_(vision, name: str) -> bool:
    """**文字锚点优先，指纹兜底**（和 describe 保持一致）。

    **被遮挡时一律返回 False**（BUG-032）：
    此时读到的可能是别的程序的画面，任何「认出来了」都是假的。
    返回 False 会让调用方继续等/继续按 ESC —— 那才是对的。
    """
    if getattr(vision, "occluded", False):
        return False
    for a in ANCHORS:
        if a.name == name:
            if a.match(vision):
                return True
            # 文字没中，再看指纹（可能这个界面没有文字特征）
            return detect_by_fingerprint(vision) == name
    return False


def wait(vision, name: str, timeout: float = 10.0) -> bool:
    import time
    t0 = time.time()
    while time.time() - t0 < timeout:
        if is_(vision, name):
            return True
        time.sleep(0.15)
    return False


# 帧号 → describe 结果（只缓存最近若干帧）
_DESC_CACHE: dict = {}


def describe(vision) -> str:
    """**文字锚点优先，指纹兜底。**

    为什么改（2026-11-26）：指纹是「打分最近者」，文字锚点是「must 全中」。
    实测点「更多」后，文字锚点明明能命中「更多功能」，
    但 `state/fingerprints.json` 里没有这个新面板，指纹把它归成了
    「驱动盘拆解页」—— **精确的被模糊的盖住了。**

    指纹的定位应该是「文字锚点认不出时兜底」，不是「优先」。
    """
    # **被遮挡时要说真话**（BUG-032）。
    # 此时读到的可能是别的程序的画面，任何「认出来了」都是假的。
    if getattr(vision, "occluded", False):
        return "被遮挡"

    # **同一帧里重复问，直接给上次答案**（性能）。
    #
    # 实测 `describe()` 要 **14.7 秒** —— 它按顺序试约 20 个锚点，
    # 每个锚点一个**不同的区域**，每个区域各 OCR 一次。
    # 而 `Machine.state()` 在一次导航里会被调很多次（go_to 判状态、
    # run 判成败、verify 再判一次），**同一帧被反复问同一个问题**。
    #
    # 用 `_frame_key()` 做缓存键：`frame(force=True)` 会换 key，
    # 所以「新画面」自动失效，不会读到旧结论。
    vk = None
    try:
        vk = (id(vision), vision._frame_key())
    except Exception:
        pass
    if vk is not None:
        hit = _DESC_CACHE.get(vk)
        if hit is not None:
            return hit

    # **检测期间冻结帧** —— 这既是性能问题，更是**正确性问题**。
    #
    # `_cache_ms` 默认 120 毫秒，而 `describe()` 实测要 **14 秒**
    # （按顺序试约 20 个锚点，每个一个不同区域，各 OCR 一次）。
    # 也就是说：**同一次 `describe()` 里，第 1 个锚点和第 20 个锚点
    # 拿到的是不同的帧**。
    #
    # 这在界面切换的过渡动画里会给出自相矛盾的结论 ——
    # 前几个锚点在旧画面上判否，后面几个在新画面上判是。
    # `describe()` 应该回答「**这一帧**是什么界面」，不是「过去 14 秒里出现过什么」。
    #
    # 冻结后还有一个副产品：所有区域 OCR 共用同一帧，缓存全部命中。
    _old_cache_ms = getattr(vision, "_cache_ms", None)
    try:
        if _old_cache_ms is not None:
            vision._cache_ms = 10 ** 9          # 期间不再抓新帧
        a = detect(vision)                   # 精确：must 全中
        fp_name = None if a else detect_by_fingerprint(vision)   # 兜底：打分最近
    finally:
        if _old_cache_ms is not None:
            vision._cache_ms = _old_cache_ms

    out = a.name if a else (fp_name or "未知界面")
    if vk is not None:
        if len(_DESC_CACHE) > 32:
            _DESC_CACHE.clear()
        _DESC_CACHE[vk] = out
    return out
    out = fp_name or "未知界面"
    if vk is not None:
        # 只留最近几帧，别无限涨
        if len(_DESC_CACHE) > 32:
            _DESC_CACHE.clear()
        _DESC_CACHE[vk] = out
    return out